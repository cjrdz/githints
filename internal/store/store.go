// Package store wraps the SQLite-backed change log that lives at
// .githints/store.db. It is the single source of truth; everything in
// the per-file markdown and CHANGES.md is rendered from these rows.
package store

import (
	"database/sql"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
	"sync"

	_ "modernc.org/sqlite"

	"github.com/cjrdz/githints/internal/gitutil"
	"github.com/cjrdz/githints/internal/safefs"
)

// ClockSkewTolerance is how many seconds a new recorded_at is allowed to
// be earlier than the previous one before we flag it as possible clock
// tampering. Small negative jumps happen on concurrent inserts; large
// jumps are suspicious.
const ClockSkewTolerance = 5

type Store struct {
	db *sql.DB

	// mu protects lastRecordedAt. Concurrent Record() calls can race on
	// the ordering timestamp; the mutex lets us detect backward jumps
	// relative to the most recent value we have seen in this process.
	mu             sync.Mutex
	lastRecordedAt int64
}

// Change is one row in the change log. recorded_at is generated by the Go
// process (time.Now().Unix()) and compared monotonically against the previous
// maximum, which is persisted in githints_meta.last_recorded_at. This detects
// backward clock jumps (rollback) but does not prevent arbitrary future
// timestamps. hmac + prev_hmac form a chain that makes the log tamper-evident.
// diff_hash binds the actual unified diff content into that chain.
// clock_tamper_warning is set when a row's recorded_at jumps backward by more
// than ClockSkewTolerance seconds.
type Change struct {
	ID                 int64
	FilePath           string
	CommitHash         string
	Branch             string
	Source             string // "agent", "llm", or "fallback"
	Summary            string
	Reason             string
	DiffStat           string
	DiffHash           string
	AgentID            string
	RecordedAt         int64
	HMAC               string
	PrevHMAC           string
	ClockTamperWarning bool
	CreatedAt          string

	// Kind is KindChange for a recorded edit and KindOutcome for a later
	// statement about one. An outcome row names its target by id; the target's
	// diff_hash at that time rides along so a mismatch is detectable. These
	// four fields are signed (see integrity.hmacPayload) and omitted from the
	// payload for ordinary changes, so rows written before they existed keep
	// verifying.
	Kind           string
	TargetID       int64
	TargetDiffHash string
	OutcomeState   string

	// A review receipt (KindReview) says a review of one exact staged tree
	// reached Verdict. CandidateTree is the tree `git write-tree` gave for
	// the index and BaseCommit the HEAD it was staged on. The post-commit hook
	// stamps commit_hash on every receipt whose tree and base the commit
	// matches, which uses it up: a receipt is never valid twice. Signed like
	// the outcome fields, and omitted from the payload when empty.
	CandidateTree string
	BaseCommit    string
	Verdict       string

	// LatestOutcome is display-only: the newest outcome row recorded for this
	// change, attached by the readers that list changes. It is never stored
	// or signed.
	LatestOutcome *Change
}

// MetaAnchorsPushed holds the anchors ref as `githints anchors push` last
// sent it, so doctor can tell whether newer anchors are still only local
// without asking the remote.
const MetaAnchorsPushed = "anchors_pushed"

// Row kinds.
const (
	KindChange  = "change"
	KindOutcome = "outcome"
	KindReview  = "review"
)

// Review verdicts. Only an approval lets a high-risk change through the
// pre-commit gate; escalated means a person must decide, inconclusive that the
// review did not finish.
const (
	VerdictApproved     = "approved"
	VerdictEscalated    = "escalated"
	VerdictInconclusive = "inconclusive"
)

// ValidVerdict reports whether s is a verdict a review receipt may carry.
func ValidVerdict(s string) bool {
	switch s {
	case VerdictApproved, VerdictEscalated, VerdictInconclusive:
		return true
	}
	return false
}

// Outcome states, in the order they are documented to agents.
const (
	OutcomeWorked   = "worked"
	OutcomePartial  = "partial"
	OutcomeFailed   = "failed"
	OutcomeReverted = "reverted"
	OutcomeUnknown  = "unknown"
)

// ValidOutcome reports whether s is a state an outcome row may carry.
func ValidOutcome(s string) bool {
	switch s {
	case OutcomeWorked, OutcomePartial, OutcomeFailed, OutcomeReverted, OutcomeUnknown:
		return true
	}
	return false
}

// changeColumns is the one column list every reader selects, in the order
// scanChanges reads it. Queries alias the table as c.
const changeColumns = `c.id, c.file_path, COALESCE(c.commit_hash,''), COALESCE(c.branch,''), c.source, c.summary, COALESCE(c.reason,''), COALESCE(c.diff_stat,''), COALESCE(c.diff_hash,''), COALESCE(c.agent_id,''), c.recorded_at, COALESCE(c.hmac,''), COALESCE(c.prev_hmac,''), c.clock_tamper_warning, c.created_at, c.kind, c.target_id, c.target_diff_hash, c.outcome, c.candidate_tree, c.base_commit, c.verdict`

